import Ajv from 'ajv/dist/2020.js';
import standalone from 'ajv/dist/standalone/index.js';
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const descriptor = JSON.parse(await readFile(new URL('examples/semantic/board.json', root)));
const schemas = new Map([descriptor.stateSchema, ...descriptor.actions.flatMap(a => [a.inputSchema, a.outputSchema])].map(s => [s.$id, s]));
const ajv = new Ajv({ strict: true, code: { source: true, esm: true, lines: true } });
for (const schema of schemas.values()) ajv.addSchema(schema);
const names = Object.fromEntries([...schemas.keys()].map((id, i) => [`schema${i}`, id]));
const result = '// Generated by npm run build:semantic; do not edit. Ajv 8.20.0 (MIT).\n' + standalone(ajv, names);
// A browser fixture must not silently acquire Node-only helpers.
if (/\brequire\(/.test(result)) throw new Error('Standalone output unexpectedly requires a runtime helper');
const path = new URL('examples/semantic/validators.js', root);
if (process.argv.includes('--check')) {
  if (await readFile(path, 'utf8') !== result) throw new Error('Semantic validators have drifted');
} else await writeFile(path, result);
console.log(JSON.stringify({ validators: schemas.size, status: 'MATCH' }));
