import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { mkdir, writeFile } from 'node:fs/promises';

const args = process.argv.slice(2), option = name => { const i = args.indexOf(name); return i < 0 ? undefined : args[i + 1]; };
const modulePath = option('--playwright-module'), executablePath = option('--browser-executable');
const url = new URL(option('--url') || 'http://127.0.0.1:8022/semantic/');
const output = option('--output') || '/tmp/hoh-semantic-browser';
if (!modulePath || !executablePath || url.protocol !== 'http:' || url.hostname !== '127.0.0.1') throw new Error('Use explicit local Playwright/browser paths and loopback preview');
await mkdir(output, { recursive: true });
const { chromium } = createRequire(import.meta.url)(resolve(modulePath));
const browser = await chromium.launch({ executablePath, headless: true });
const checks = [], errors = [], check = (value, name) => { if (!value) throw new Error(name); checks.push(name); };
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, colorScheme: 'dark', reducedMotion: 'reduce' });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(url.href, { waitUntil: 'networkidle' });
  await page.locator('.semantic-board').waitFor();
  const read = () => page.evaluate(() => window.hohSemanticExample.read());
  const submit = async message => { await page.locator('#chatInput').fill(message); await page.locator('#chatForm').evaluate(form => form.requestSubmit()); await page.waitForFunction(() => !document.querySelector('#chatForm button').disabled); };
  check(await page.locator('.chat').isVisible(), 'content and adjacent chat are visible');
  check((await page.locator('#chatStatus').textContent()).includes('규칙 기반'), 'demo clearly identifies deterministic planner and disconnected HSWM');
  check((await read()).stateRevision === 0, 'visiting content does not mutate its state');
  await page.locator('#board-title').fill('사람이 만든 제목'); await page.locator('[data-title-form] button').click();
  await page.waitForFunction(() => document.querySelector('.semantic-board h2').textContent === '사람이 만든 제목');
  check((await read()).stateRevision === 1, 'human form commits through the runtime');
  await submit('추가: AI와 준비하는 회의');
  await page.waitForFunction(() => document.querySelectorAll('.task-toggle').length === 3);
  check((await read()).state.tasks.at(-1).label === 'AI와 준비하는 회의', 'chat command changes the same visible content');
  check(await page.locator('[data-history]').textContent().then(text => text.includes('채팅 명령') && text.includes('직접 조작')), 'receipts distinguish human and agent origin');
  await submit('완료 1');
  check((await read()).state.tasks[0].done, 'agent command toggles a human-visible task');
  await page.locator('.task-toggle').first().click();
  check(!(await read()).state.tasks[0].done, 'human can change a task after the agent');
  await submit('삭제 1');
  check((await read()).state.tasks.length === 3, 'destructive proposal is not executed before confirmation');
  await page.locator('.proposal button', { hasText: '취소' }).last().click();
  check((await read()).state.tasks.length === 3, 'cancelling a proposal preserves content');
  await submit('삭제 1');
  await page.locator('#board-title').fill('제안 뒤에 사람이 수정'); await page.locator('[data-title-form] button').click();
  await page.locator('.proposal button', { hasText: '변경 적용' }).last().click();
  check((await read()).state.tasks.length === 3, 'stale confirmed agent proposal cannot overwrite a human edit');
  check(await page.locator('.proposal').last().textContent().then(text => text.includes('내용이 바뀌었어요')), 'revision conflict is visible and recoverable');
  await submit('삭제 1'); await page.locator('.proposal button', { hasText: '변경 적용' }).last().click();
  await page.waitForFunction(() => document.querySelectorAll('.task-toggle').length === 2);
  check((await read()).state.tasks.length === 2, 'fresh confirmed action commits once');
  await submit('아무 말이나 실행');
  check(await page.locator('#messages').textContent().then(text => text.includes('명령 예제:')), 'unsupported natural language produces help rather than fake execution');
  check(await page.locator('[data-action-id]').evaluateAll(nodes => new Set(nodes.map(node => node.dataset.actionId)).size) === 5, 'every board domain action has a visible human control');
  await submit('초기화');
  await page.locator('[data-next]').click();
  check(await page.locator('.proposal').last().textContent().then(text => text.includes('콘텐츠를 이동')), 'navigation cancels a pending agent proposal');
  check((await read()).state.tasks.length === 2, 'cancelled navigation proposal causes no reset');
  await page.evaluate(() => window.hohSemanticExample.ui.open('urn:hoh:example:board'));
  await page.screenshot({ path: `${output}/semantic-desktop.png`, fullPage: true });
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width}px has no document horizontal overflow`);
    check(await page.locator('.semantic-board button').evaluateAll(nodes => nodes.every(node => { const b = node.getBoundingClientRect(); return b.width >= 44 && b.height >= 44; })), `${width}px content actions meet 44px targets`);
  }
  await page.setViewportSize({ width: 390, height: 844 }); await page.locator('#sheetHandle').click();
  await page.waitForFunction(() => document.querySelector('.chat').getBoundingClientRect().height > 44);
  check(await page.locator('.chat').boundingBox().then(box => box.height > 44), 'mobile supports shared content and half-height chat');
  await page.screenshot({ path: `${output}/semantic-mobile.png`, fullPage: true });
  await page.setViewportSize({ width: 1440, height: 960 }); await page.emulateMedia({ colorScheme: 'light' });
  await page.locator('#board-title').focus(); await page.keyboard.press('Control+A'); await page.keyboard.type('Keyboard title'); await page.keyboard.press('Enter');
  check((await read()).state.title === 'Keyboard title', 'keyboard-only title editing works');
  await page.screenshot({ path: `${output}/semantic-light.png`, fullPage: true });
  check(errors.length === 0, 'no browser runtime errors');
  await writeFile(`${output}/result.json`, JSON.stringify({ status: 'PASS', checks, errors }, null, 2));
  console.log(JSON.stringify({ status: 'PASS', passed: checks.length, checks }));
} finally { await browser.close(); }
